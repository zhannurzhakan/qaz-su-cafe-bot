/** Слова, с которых начинается заявка (если ещё не в режиме заявки). */
export const INTAKE_TRIGGER_RE = /заброни|бронь|броню|брониров|заявк|столик|брондау|үстел/iu;

const YES_WORDS = new Set([
  "да", "верно", "всё", "все", "подтверждаю", "подтверждаем", "ага", "ок", "окей", "ok", "конечно",
  "давайте", "иә", "ия", "дұрыс", "растаймын", "растау",
]);

/** «Да», «да, всё верно», «иә» и т.п. — но не «да, только время другое». */
export function isYes(text) {
  const words = text.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, " ").split(/\s+/).filter(Boolean);
  return words.length > 0 && words.every((w) => YES_WORDS.has(w));
}

const NO_RE = /^\s*(?:нет|не\s*верно|неверно|не\s*так|изменить|исправить|поменять|жоқ|өзгерт)(?![\p{L}])/iu;

/** Если гость не подтвердил: возвращает остаток сообщения после слова «нет» (возможно, пустой). */
export function parseNo(text) {
  if (!NO_RE.test(text)) return null;
  return text.replace(NO_RE, "").replace(/^[\s,.!:;—-]+/, "");
}

