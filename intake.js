    "",
    "Верни ТОЛЬКО один JSON-объект: без текста до и после, без markdown и без ```.",
    "Поля:",
    '- "intent": "booking", если гость хочет забронировать столик или отвечает на вопрос по заявке; "other", если сообщение не про бронь (вопрос о меню, приветствие, шутка и т.п.);',
