const KEYS = ["intent", "date", "time", "guests", "name", "phone", "missing"];

/** Разбирает ответ модели. Бросает Error, если это не JSON нужной формы. */
export function parseIntakeJson(raw) {
  // Единственное послабление: убираем ограду ```json … ```, если модель её всё-таки поставила.
  const text = String(raw).trim().replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "").trim();
  const d = JSON.parse(text);
  if (!d || typeof d !== "object" || Array.isArray(d)) throw new Error("не объект");
  for (const k of KEYS) if (!(k in d)) throw new Error(`нет поля ${k}`);
  if (typeof d.intent !== "string") throw new Error("intent не строка");
  if (!Array.isArray(d.missing) || !d.missing.every((x) => typeof x === "string")) {
    throw new Error("missing не список строк");
  }
  const val = (v) => {
    if (v === null || v === undefined) return null;
    if (typeof v === "string") return v.trim() === "" ? null : v.trim();
    if (typeof v === "number" && Number.isFinite(v)) return v;
    throw new Error("недопустимый тип поля");
  };
  return {
    intent: d.intent.trim().toLowerCase(),
    date: val(d.date),
    time: val(d.time),
    guests: val(d.guests),
    name: val(d.name),
    phone: val(d.phone),
    missing: d.missing,
  };
}

