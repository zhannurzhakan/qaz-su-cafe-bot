async function main() {
  if (!process.env.OPENROUTER_API_KEY) {
    console.error("OPENROUTER_API_KEY не найден в .env");
    return 1;
  }
  const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "cafe-hard-")), "bookings.csv");
  const bot = new CafeAssistant(new LLM(process.env.OPENROUTER_API_KEY, DEFAULT_MODELS), tmp);
  console.log(`Трудных вопросов: ${CASES.length}. Модели: ${DEFAULT_MODELS.join(", ")}\n`);

  let id = 9000;
  for (const [i, [title, question, expected]] of CASES.entries()) {
    console.log(`\n${"=".repeat(70)}\n${i + 1}. ${title}\n${"=".repeat(70)}`);
    console.log(`ГОСТЬ: ${question}\nОЖИДАЕТСЯ: ${expected}\n`);
    try {
      const r = await bot.chat(++id, question, { username: "test", setLang: true });
      console.log(`\nБОТ: ${r.text.replaceAll("\n", "\n     ")}`);
    } catch (e) {
      console.log(`\nОШИБКА: ${e.message}`);
    }
  }
  console.log("\nГотово. Сравните ответы бота с пунктом «ОЖИДАЕТСЯ»; строки WARNING показывают, где проверка кода забраковала ответ.");
  return 0;
}

process.exitCode = await main();
